create policy "Allow all" on public.content_calendar  for all to anon, authenticated using (true) with check (true);
create policy "Allow all" on public.content_review    for all to anon, authenticated using (true) with check (true);
create policy "Allow all" on public.live_posts        for all to anon, authenticated using (true) with check (true);
create policy "Allow all" on public.payment_status    for all to anon, authenticated using (true) with check (true);
